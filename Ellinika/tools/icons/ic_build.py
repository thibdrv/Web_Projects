import sys, json, re, importlib, glob, os
sys.path.insert(0, os.path.dirname(__file__))
import ic_lib
mods=[]
for n in ["ic_a","ic_b","ic_c","ic_d","ic_e","ic_f","ic_g","ic_h"]:
    try: importlib.import_module(n); mods.append(n)
    except ModuleNotFoundError as ex:
        if ex.name!=n: raise
FE=re.compile("\uFE0F")
ICONS=ic_lib.ICONS; ALIAS=ic_lib.ALIAS; MONO=ic_lib.MONO
# keys normalised (no FE0F)
ICONS={FE.sub("",k):v for k,v in ICONS.items()}
ALIAS={FE.sub("",k):FE.sub("",v) for k,v in ALIAS.items()}
MONO={FE.sub("",k) for k in MONO}
# used emoji (survey)
sys.path.insert(0,os.path.dirname(__file__))
EM=re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\u2190-\u21FF\u2300-\u23FF\u25A0-\u25FF\u2900-\u297F\U0001F1E6-\U0001F1FF]\uFE0F?(?:\u200D[\U0001F000-\U0001FAFF\u2600-\u27BF]\uFE0F?)*")
root=os.path.abspath(os.path.join(os.path.dirname(__file__),"..",".."))
used={}
for pat in ["index.html","js/*.js","css/*.css","data/*.js"]:
    for f in glob.glob(os.path.join(root,pat)):
        if f.endswith("icons.js") or f.endswith("iconify.js") or f.endswith("fr.js"): continue
        t=open(f,encoding="utf-8",errors="ignore").read()
        for m in EM.findall(t):
            k=FE.sub("",m)
            # flags: merge regional indicator pairs
            used.setdefault(k,set()).add(os.path.basename(f))
# merge the lone regional indicators into pairs (the data writes flags as pairs)
KEEP=set("→ ← ↔ ↑ ↓ ↗ ↖ ↘ ↙".split())
missing=[k for k in used if k not in ICONS and k not in ALIAS and k not in KEEP and not (len(k)==1 and 0x1F1E6<=ord(k)<=0x1F1FF)]
print("modules:",mods,"icons:",len(ICONS),"aliases:",len(ALIAS),"missing:",len(missing))
print(" ".join(missing))

# ---------- outputs ----------
out=os.path.join(root,"data","icons.js")
def esc(s): return json.dumps(s, ensure_ascii=False)
lines=["/* ---------- the pictures: every emoji of the app is drawn here as a small SVG (viewBox 0 0 32 32) ----------",
 "   The key is the emoji character (without the variation selector U+FE0F). js/iconify.js replaces each emoji of the page by its drawing.",
 "   Generated by a script; the icons that use currentColor (ICON_MONO) take the colour of the text around them. */",
 "const ICONS = {"]
for k in sorted(ICONS): lines.append("  %s: %s," % (esc(k), esc(ICONS[k])))
lines.append("};")
lines.append("const ICON_ALIAS = %s;" % json.dumps(ALIAS, ensure_ascii=False))
lines.append("const ICON_MONO = %s;" % json.dumps(sorted(MONO), ensure_ascii=False))
open(out,"w",encoding="utf-8").write("\n".join(lines)+"\n")
print("written", os.path.getsize(out)//1024, "KB")
# contact sheet
cells=[]
for k in sorted(ICONS):
    cells.append('<div class="c"><svg viewBox="0 0 32 32" width="64" height="64" style="%s">%s</svg><small>%s</small></div>' % ("color:#333" if k in MONO else "", ICONS[k], k))
open(os.path.join(os.path.dirname(__file__),"sheet.html"),"w",encoding="utf-8").write('<!doctype html><meta charset="utf-8"><style>body{font:10px sans-serif;background:#fff;margin:6px}.c{display:inline-block;width:70px;text-align:center;margin:2px}small{display:block;color:#666;font-size:12px}</style>'+"".join(cells))
