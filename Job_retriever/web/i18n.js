let LANG = "fr";

function t(key, vars = {}) {
  const text = (I18N[LANG] && I18N[LANG][key]) ?? I18N.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

// Stored offers always keep their French values; this is how they read in English.
function displayValue(header, value) {
  if (LANG !== "en" || typeof value !== "string") return value;
  if (header === "Expérience") {
    const years = value.match(/^(\d+)\+ ans$/);
    if (years) return `${years[1]}+ years`;
    return { "non précisé": "not specified", "page non lue": "page not read" }[value] ?? value;
  }
  if (header === "Entreprise") return value.replace("(pour un client)", "(for a client)");
  return value;
}
